#!/usr/bin/env node
/**
 * Round 7 test (spike.md): can our own wpc:wpc canvas -- the one
 * ooxml-translator.ts already uses for every non-SmartArt flowchart,
 * subgraph title boxes included -- host a real SmartArt diagram
 * (wpc:graphicFrame, per MS-ODRAWXML's CT_WordprocessingCanvas content
 * model) as a sibling of an ordinary wps:wsp shape?
 *
 * Builds one wpc:wpc canvas containing:
 *   1. A plain wps:wsp rectangle with a title ("Sous-groupe (titre)"),
 *      mimicking today's subgraph title box.
 *   2. A wpc:graphicFrame directly below it, wrapping a real, self-authored
 *      2-node `chain` SmartArt -- generated by importing the actual shipped
 *      generateChain() from @md2nativedocx/core, not a hand-copied XML
 *      fixture, so this test tracks the real generator if it changes.
 *
 * Result (2026-09-03, headless LibreOffice): the rectangle renders
 * correctly; the embedded diagram does not appear at all -- the canvas's
 * own frame extent shrinks to fit only the rectangle, as if the
 * wpc:graphicFrame sibling were entirely absent. Consistent with
 * LibreOffice's WordprocessingML filter not implementing this rare 2010
 * extension, not an XML mistake (the schema was followed exactly, sourced
 * from Microsoft Learn's MS-ODRAWXML docs, not memory -- see spike.md
 * Round 7 for the citations). Sent to the maintainer to check in real Word;
 * verdict pending.
 *
 * Standalone exploratory script (AGENTS.md rules #3/#4/#5/#7 apply and are
 * respected identically to the other build-*.mjs scripts in this
 * directory), except it imports the real shipped generator from
 * @md2nativedocx/core rather than a hand-authored XML fixture -- this round
 * is specifically testing whether our own generator's real output can be
 * embedded this way, not re-deriving a chain diagram from scratch.
 *
 * Usage: node build-custom-nested-canvas.mjs [base.docx] [custom-nested-canvas.docx]
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateChain } from '../../../../packages/core/dist/smartart/chain.js';

const HERE = dirname(fileURLToPath(import.meta.url));

const RELTYPE = {
  data: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/diagramData',
  layout: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/diagramLayout',
  quickStyle: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/diagramQuickStyle',
  colors: 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/diagramColors',
};
const CONTENTTYPE = {
  data: 'application/vnd.openxmlformats-officedocument.drawingml.diagramData+xml',
  layout: 'application/vnd.openxmlformats-officedocument.drawingml.diagramLayout+xml',
  quickStyle: 'application/vnd.openxmlformats-officedocument.drawingml.diagramStyle+xml',
  colors: 'application/vnd.openxmlformats-officedocument.drawingml.diagramColors+xml',
};
const DGM_NS = 'http://schemas.openxmlformats.org/drawingml/2006/diagram';
const A_NS = 'http://schemas.openxmlformats.org/drawingml/2006/main';
const WPC_NS = 'http://schemas.microsoft.com/office/word/2010/wordprocessingCanvas';
const WPS_NS = 'http://schemas.microsoft.com/office/word/2010/wordprocessingShape';
const WP_NS = 'http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing';
const R_NS = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships';

function fail(msg) {
  console.error(`build-custom-nested-canvas: ${msg}`);
  process.exit(1);
}

function nextFreeRelId(relsXml, base) {
  let n = 1;
  while (relsXml.includes(`Id="${base}${n}"`)) n += 1;
  return `${base}${n}`;
}

function main() {
  const baseDocxArg = process.argv[2] ?? join(HERE, 'base.docx');
  const outDocxArg = process.argv[3] ?? join(HERE, 'custom-nested-canvas.docx');
  const baseDocx = resolve(baseDocxArg);
  const outDocx = resolve(outDocxArg);

  if (!existsSync(baseDocx)) fail(`base docx not found at ${baseDocx}`);

  const flowchart = {
    nodes: [
      { id: 'A', label: 'Interne 1' },
      { id: 'B', label: 'Interne 2' },
    ],
    edges: [{ from: 'A', to: 'B', type: 'arrow', label: null }],
    subgraphs: [],
    direction: 'LR',
  };
  const { dataXml, layoutXml, colorsXml, styleXml } = generateChain(flowchart);

  const work = mkdtempSync(join(tmpdir(), 'nested-canvas-'));
  try {
    execFileSync('unzip', ['-o', '-q', baseDocx, '-d', work]);

    const diagramsDir = join(work, 'word', 'diagrams');
    mkdirSync(diagramsDir, { recursive: true });
    writeFileSync(join(diagramsDir, 'data1.xml'), dataXml, 'utf8');
    writeFileSync(join(diagramsDir, 'layout1.xml'), layoutXml, 'utf8');
    writeFileSync(join(diagramsDir, 'colors1.xml'), colorsXml, 'utf8');
    writeFileSync(join(diagramsDir, 'quickStyle1.xml'), styleXml, 'utf8');

    const contentTypesPath = join(work, '[Content_Types].xml');
    let contentTypes = readFileSync(contentTypesPath, 'utf8');
    if (!contentTypes.includes('</Types>')) fail('[Content_Types].xml has no </Types>');
    const overrides = ['data', 'layout', 'quickStyle', 'colors']
      .map((k) => `<Override PartName="/word/diagrams/${k === 'quickStyle' ? 'quickStyle1' : k + '1'}.xml" ContentType="${CONTENTTYPE[k]}" />`)
      .join('');
    contentTypes = contentTypes.replace('</Types>', `${overrides}</Types>`);
    writeFileSync(contentTypesPath, contentTypes, 'utf8');

    const relsPath = join(work, 'word', '_rels', 'document.xml.rels');
    let relsXml = readFileSync(relsPath, 'utf8');
    if (!relsXml.includes('</Relationships>')) fail('document.xml.rels has no </Relationships>');
    const rId = {};
    for (const k of ['data', 'layout', 'quickStyle', 'colors']) {
      rId[k] = nextFreeRelId(relsXml, `rIdNested${k[0].toUpperCase()}${k.slice(1)}`);
      const target = k === 'quickStyle' ? 'diagrams/quickStyle1.xml' : `diagrams/${k}1.xml`;
      relsXml = relsXml.replace('</Relationships>', `<Relationship Id="${rId[k]}" Type="${RELTYPE[k]}" Target="${target}" /></Relationships>`);
    }
    if (relsXml.includes('TargetMode="External"')) {
      fail('refusing to write a document.xml.rels containing an external relationship');
    }
    writeFileSync(relsPath, relsXml, 'utf8');

    const documentPath = join(work, 'word', 'document.xml');
    let documentXml = readFileSync(documentPath, 'utf8');
    const rootStart = documentXml.indexOf('<w:document');
    const rootTagEnd = documentXml.indexOf('>', rootStart);
    if (rootStart < 0 || rootTagEnd < 0) fail('could not find <w:document> root element');
    const rootOpenTag = documentXml.slice(rootStart, rootTagEnd + 1);
    const needed = { 'xmlns:dgm': DGM_NS, 'xmlns:wpc': WPC_NS, 'xmlns:wps': WPS_NS, 'xmlns:wp': WP_NS, 'xmlns:a': A_NS, 'xmlns:r': R_NS };
    let newOpenTag = rootOpenTag;
    for (const [attr, uri] of Object.entries(needed)) {
      if (!newOpenTag.includes(`${attr}=`)) newOpenTag = newOpenTag.replace('>', ` ${attr}="${uri}">`);
    }
    documentXml = documentXml.slice(0, rootStart) + newOpenTag + documentXml.slice(rootTagEnd + 1);

    // A wpc:wpc canvas hosting BOTH a plain rectangle (mimicking a subgraph
    // title/frame box) and a wpc:graphicFrame embedding the real SmartArt
    // diagram, side by side in the same canvas coordinate space.
    const canvasWidth = 5486400;
    const canvasHeight = 3600000;
    const rectHeight = 500000;
    const diagramTop = rectHeight + 100000;
    const diagramHeight = canvasHeight - diagramTop;

    const rectangle =
      '<wps:wsp>' +
      '<wps:cNvPr id="101" name="SubgraphTitle"/>' +
      '<wps:cNvSpPr/>' +
      '<wps:spPr>' +
      `<a:xfrm><a:off x="0" y="0"/><a:ext cx="${canvasWidth}" cy="${rectHeight}"/></a:xfrm>` +
      '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom>' +
      '<a:noFill/>' +
      '<a:ln><a:solidFill><a:srgbClr val="000000"/></a:solidFill></a:ln>' +
      '</wps:spPr>' +
      '<wps:txbx><w:txbxContent><w:p><w:r><w:t>Sous-groupe (titre)</w:t></w:r></w:p></w:txbxContent></wps:txbx>' +
      '<wps:bodyPr/>' +
      '</wps:wsp>';

    const graphicFrame =
      '<wpc:graphicFrame>' +
      '<wpc:cNvPr id="102" name="NestedSmartArt"/>' +
      '<wpc:cNvFrPr/>' +
      `<a:xfrm><a:off x="0" y="${diagramTop}"/><a:ext cx="${canvasWidth}" cy="${diagramHeight}"/></a:xfrm>` +
      `<a:graphic><a:graphicData uri="${DGM_NS}">` +
      `<dgm:relIds r:dm="${rId.data}" r:lo="${rId.layout}" r:qs="${rId.quickStyle}" r:cs="${rId.colors}"/>` +
      '</a:graphicData></a:graphic>' +
      '</wpc:graphicFrame>';

    const drawingParagraph =
      '<w:p><w:r><w:drawing>' +
      '<wp:inline distT="0" distB="0" distL="0" distR="0">' +
      `<wp:extent cx="${canvasWidth}" cy="${canvasHeight}"/>` +
      '<wp:effectExtent l="0" t="0" r="0" b="0"/>' +
      '<wp:docPr id="9040" name="Nested Test"/>' +
      '<wp:cNvGraphicFramePr><a:graphicFrameLocks noChangeAspect="1"/></wp:cNvGraphicFramePr>' +
      `<a:graphic><a:graphicData uri="http://schemas.microsoft.com/office/word/2010/wordprocessingCanvas">` +
      '<wpc:wpc>' +
      '<wpc:bg><a:solidFill><a:prstClr val="white"/></a:solidFill></wpc:bg>' +
      '<wpc:whole/>' +
      rectangle +
      graphicFrame +
      '</wpc:wpc>' +
      '</a:graphicData></a:graphic>' +
      '</wp:inline></w:drawing></w:r></w:p>';

    const bodyEndIdx = documentXml.indexOf('</w:body>');
    if (bodyEndIdx < 0) fail('could not find </w:body>');
    const sectPrIdx = documentXml.lastIndexOf('<w:sectPr');
    const insertAt = sectPrIdx >= 0 && sectPrIdx < bodyEndIdx ? sectPrIdx : bodyEndIdx;
    documentXml = documentXml.slice(0, insertAt) + drawingParagraph + documentXml.slice(insertAt);
    writeFileSync(documentPath, documentXml, 'utf8');

    if (existsSync(outDocx)) rmSync(outDocx);
    execFileSync('zip', ['-X', '-r', '-q', outDocx, '.'], { cwd: work });
    console.log(`build-custom-nested-canvas: wrote ${outDocx}`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

main();
